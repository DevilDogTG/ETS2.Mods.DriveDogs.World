#!/usr/bin/env python3
"""
Generates world/sign_frames.yaml: base-game sign frame definitions scaled to the frame texture that wins in the
build, as edits of the current base game (megapack `base_edits`).

Frame definitions (`def/sign/frame/*.sii`, *_coords_l/r/b/t) give texture coordinates in pixels. DBM Road Signs
ships 4x frame textures with its own scaled definitions, but only for the frames that existed when it was made.
A frame the base game adds later on the same material keeps the base game's small numbers, and the game draws a
quarter of the frame image (1.62 added eight UK frames, `frame_*2_uk` and `frame_blue3_uk`, on DBM's 128x128 UK
frame textures with 32x32 coordinates). Decisions: plan world-base-162; check: tools/check_sign_defs.py.

A frame is edited when the base game owns its definition (no source or overrides/ file ships it) and a source
wins its texture at a size other than the base game's: every coordinate is scaled by (winning size / base size).
Winners come from the lock and overrides/, so rerun this tool after `megapack lock` and after a game update.
Sign atlases (`def/sign/atlas/`) are not handled here; check_sign_defs.py reports any that would need it.

usage: python tools/sign_frames.py [--check]    (--check: fail if world/sign_frames.yaml would change)
Inputs: the extracted base game of this host (profile host file) at the version in megapack.yaml, lock/.
"""
from __future__ import annotations

import argparse
import re
import sys

import yaml

from check_sign_defs import FRAME_KEY, MATERIAL, ROOT, Tree, dds_size, read, texture

OUT = ROOT / "world" / "sign_frames.yaml"
UNIT = re.compile(r"^sign_frame_template\s*:\s*(\S+)\s*\n\{(.*?)^\}", re.M | re.S)


def number(v: float) -> str:
    return str(int(v)) if v == int(v) else f"{v:g}"


def scan(tree: Tree) -> dict[str, dict[str, dict]]:
    edits: dict[str, dict[str, dict]] = {}
    for rel in tree.defs():
        if not rel.startswith("def/sign/frame/"):
            continue
        owner, def_file = tree.find(rel)
        if owner != "base" or def_file is None:
            continue
        for unit, body in UNIT.findall(read(def_file)):
            mat = MATERIAL.search(body)
            tex = texture(tree, mat.group(1), base_only=False) if mat else None
            if tex is None or tex[0] == "base":
                continue
            base_tex = texture(tree, mat.group(1), base_only=True)
            if base_tex is None:
                sys.exit(f"{rel}: base game texture of {mat.group(1)} not found")
            (w, h), (bw, bh) = dds_size(tex[1]), dds_size(base_tex[1])
            if (w, h) == (bw, bh):
                continue
            keys = {k: number(float(v) * (w / bw if k[-1] in "lr" else h / bh)) for k, v in FRAME_KEY.findall(body)}
            edits.setdefault(rel, {})[unit] = {"set": dict(sorted(keys.items()))}
    return edits


def render(edits: dict) -> str:
    head = (
        "# GENERATED by tools/sign_frames.py — do not edit by hand; change the script and rerun it.\n"
        "# Base-game sign frames whose texture a source wins at another size, scaled to that texture's pixels.\n")
    return head + yaml.safe_dump(edits, sort_keys=False, allow_unicode=True, width=10_000)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    edits = scan(Tree())
    text = render(edits)
    n = sum(len(u) for u in edits.values())
    if args.check:
        same = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print(f"{OUT.relative_to(ROOT)} {'up to date' if same else 'OUT OF DATE'} ({len(edits)} files, {n} units)")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(edits)} files, {n} units")
    return 0


if __name__ == "__main__":
    sys.exit(main())
